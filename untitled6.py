# -*- coding: utf-8 -*-
import os
import joblib
import streamlit as st
import torch
import torch.nn as nn
import torchvision.transforms as transforms
from PIL import Image

st.set_page_config(
    page_title="Melanoma Cancer Detection",
    page_icon="🩺",
    layout="centered"
)

st.title("🩺 Melanoma Cancer Detection")
st.write(
    "Upload a skin-lesion image and the trained CNN will classify it as "
    "**benign** or **malignant**."
)

st.warning(
    "This is an educational AI model and is not a medical diagnosis. "
    "Please consult a qualified healthcare professional for any concerning skin lesion."
)

# ============================================================
# Original CNN architecture - kept unchanged
# ============================================================
class MelanomaCNN(nn.Module):
    def __init__(self):
        super(MelanomaCNN, self).__init__()
        self.features = nn.Sequential(
            nn.Conv2d(3, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),

            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),

            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.MaxPool2d(2, 2)
        )

        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(128 * 16 * 16, 128),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(128, 2)
        )

    def forward(self, x):
        x = self.features(x)
        x = self.classifier(x)
        return x


BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "melanoma_cnn_model.joblib")

# Same preprocessing used by the CNN project.
transform = transforms.Compose([
    transforms.Resize((128, 128)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225]
    )
])


@st.cache_resource
def load_model():
    if not os.path.exists(MODEL_PATH):
        raise FileNotFoundError(
            "melanoma_cnn_model.joblib was not found. "
            "Upload this model file to the same GitHub repository as untitled6.py."
        )

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = MelanomaCNN().to(device)

    # The supplied .joblib contains the CNN state_dict (OrderedDict).
    state_dict = joblib.load(MODEL_PATH)
    model.load_state_dict(state_dict)
    model.eval()

    return model, device


try:
    model, device = load_model()
    st.success("Trained CNN model loaded successfully.")
except Exception as e:
    st.error(f"Could not load the CNN model: {e}")
    st.stop()


st.divider()
st.subheader("📷 Upload an image")

uploaded_file = st.file_uploader(
    "Choose a skin-lesion image",
    type=["jpg", "jpeg", "png", "bmp"]
)

if uploaded_file is not None:
    image = Image.open(uploaded_file).convert("RGB")
    st.image(image, caption="Uploaded image", use_container_width=True)

    if st.button("🔍 Detect Cancer", type="primary", use_container_width=True):
        with st.spinner("Analyzing image..."):
            input_tensor = transform(image).unsqueeze(0).to(device)

            with torch.no_grad():
                outputs = model(input_tensor)
                probabilities = torch.softmax(outputs, dim=1)[0]
                predicted_class = torch.argmax(probabilities).item()

            class_names = ["Benign", "Malignant"]
            prediction = class_names[predicted_class]
            confidence = probabilities[predicted_class].item() * 100

        if prediction == "Malignant":
            st.error(f"Prediction: **{prediction}**")
        else:
            st.success(f"Prediction: **{prediction}**")

        st.metric("Model confidence", f"{confidence:.2f}%")

        st.caption(
            "This prediction is generated by an AI model for educational purposes "
            "and is not a medical diagnosis."
        )
else:
    st.info("Upload a JPG, JPEG, PNG, or BMP image to start detection.")
